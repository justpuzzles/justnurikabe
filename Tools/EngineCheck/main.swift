// MARK: - Lesson positions: re-proven every run

func checkPosition(_ pos: LessonPosition, _ label: String, lowest: Bool) {
    var budget = 2_000_000
    check(BacktrackingSolver.countSolutions(puzzle: pos.puzzle, limit: 2, budget: &budget) == 1,
          "\(label): puzzle not unique")
    guard let step = pos.step else { check(false, "\(label): technique does not apply"); return }
    if lowest { check(pos.isLowest, "\(label): a lower technique applies first") }
    else { check(pos.targets == pos.blanks, "\(label): rule does not decide exactly the blanks") }
    check(!pos.targets.isEmpty && pos.targets.allSatisfy { pos.marks[$0] == .unknown },
          "\(label): targets not blank")
    let g = pos.puzzle.grid
    for c in step.sea { check(!pos.puzzle.solution[g.index(c)], "\(label): shades land") }
    for c in step.land { check(pos.puzzle.solution[g.index(c)], "\(label): dots sea") }
    for i in pos.marks.indices where pos.marks[i] != .unknown {
        check((pos.marks[i] == .land) == pos.puzzle.solution[i], "\(label): given mark contradicts solution")
    }
}

