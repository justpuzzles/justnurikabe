// MARK: - Report

note("\n— corpus (\(perCell) per size×tier) —")
for size in BoardSize.allCases {
    guard let s = stats[size] else { continue }
    let grades = Difficulty.allCases.map { "\($0): \(s.grades[$0, default: 0])" }.joined(separator: ", ")
    note(String(format: "%2d×%-2d boards %3d  fallbacks %2d  tier hits %3d  avg %.2fs  clues %.1f  1s %.0f%%  | %@",
                size.rawValue, size.rawValue, s.boards, s.fallbacks, s.tierHits,
                s.seconds / Double(max(s.boards, 1)),
                Double(s.clues) / Double(max(s.boards - s.fallbacks, 1)),
                100 * Double(s.ones) / Double(max(s.clues, 1)), grades))
}
note("\n— technique usage —")
for t in Technique.allCases {
    let n = techniqueCounts[t, default: 0]
    note("  \(t): \(n)")
    if !Technique.allowedAbsentFromGeneratedPuzzles.contains(t) {
        check(n > 0, "\(t) never appears in generated traces")
    }
}
if calibrate {
    note("\n— score by technique floor —")
    for d in Difficulty.allCases {
        let xs = (calibration[d] ?? []).sorted()
        guard !xs.isEmpty else { continue }
        let q = { (p: Double) in xs[min(xs.count - 1, Int(Double(xs.count) * p))] }
        note(String(format: "  %@: n=%d  p10 %.2f  p50 %.2f  p90 %.2f", "\(d)", xs.count, q(0.1), q(0.5), q(0.9)))
    }
}

note("\n\(checks) checks, \(failures) failures")
exit(failures == 0 ? 0 : 1)
