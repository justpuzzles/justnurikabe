// MARK: - Generation corpus

struct Stats {
    var boards = 0
    var fallbacks = 0
    var tierHits = 0
    var seconds = 0.0
    var grades: [Difficulty: Int] = [:]
    var clues = 0
    var ones = 0
}

var techniqueCounts: [Technique: Int] = [:]
var stats: [BoardSize: Stats] = [:]
var calibration: [Difficulty: [Double]] = [:]
var rng = SeededRandomNumberGenerator(seed: 20260926)

for size in BoardSize.allCases {
    var s = Stats()
    for tier in size.tiers {
        for _ in 0..<perCell {
            let seed = rng.next()
            let t0 = Date()
            let result = NurikabeGenerator.generate(size: size, tier: tier, seed: seed)
            s.seconds += Date().timeIntervalSince(t0)
            s.boards += 1
            if result.isFallback { s.fallbacks += 1; continue }
            if result.grade == tier { s.tierHits += 1 }
            s.grades[result.grade, default: 0] += 1
            let p = result.puzzle
            s.clues += p.clues.count
            s.ones += p.clues.filter { $0.value == 1 }.count
            let label = "\(size.rawValue)×\(size.rawValue) \(tier) seed \(seed)"

            // The layout is a real solution.
            let solutionMarks = p.solution.map { $0 ? Mark.land : Mark.sea }
            check(Rules.isSolved(solutionMarks, puzzle: p), "\(label): stored solution breaks the rules")

            // Unique (and independently so on 5×5).
            var budget = 2_000_000
            check(BacktrackingSolver.countSolutions(puzzle: p, limit: 2, budget: &budget) == 1,
                  "\(label): not unique")
            if size == .five {
                check(naiveCount(p, limit: 2) == 1, "\(label): naive enumerator disagrees on uniqueness")
            }

            // Curriculum-solvable under the RETURNED grade's ceiling (the
            // label the UI shows), and every deduction sound.
            var solveBudget = 1_000_000
            let solved = LogicalSolver.solve(puzzle: p, maxTechnique: result.grade.techniqueCeiling,
                                             budget: &solveBudget)
            check(solved.solved, "\(label): not solvable under its grade \(result.grade)")
            for step in result.trace {
                techniqueCounts[step.technique, default: 0] += 1
                check(step.decidedCount > 0, "\(label): empty \(step.technique) step")
                for cell in step.sea {
                    check(!p.solution[cell.row * p.size + cell.col],
                          "\(label): UNSOUND \(step.technique) shaded land at \(cell)")
                }
                for cell in step.land {
                    check(p.solution[cell.row * p.size + cell.col],
                          "\(label): UNSOUND \(step.technique) dotted sea at \(cell)")
                }
            }
            check(result.trace.map(\.technique).max().map { $0 <= result.grade.techniqueCeiling } ?? true,
                  "\(label): trace exceeds its grade's ceiling")
            calibration[DifficultyRater.floor(trace: result.trace), default: []]
                .append(DifficultyRater.score(trace: result.trace, size: size.rawValue))

        }
    }
    stats[size] = s
}

