import Foundation

var checks = 0
var failures = 0

func check(_ condition: Bool, _ message: @autoclosure () -> String) {
    checks += 1
    if !condition {
        failures += 1
        FileHandle.standardError.write("FAIL: \(message())\n".data(using: .utf8)!)
    }
}

func note(_ message: String) {
    FileHandle.standardError.write("\(message)\n".data(using: .utf8)!)
}

