// MARK: - Naive enumerator (independent uniqueness cross-check)

/// Row-major cell-by-cell enumeration with only pool and count pruning,
/// then the full rule check at each leaf. Slow and obviously correct; used
/// on 5×5 boards only.
func naiveCount(_ puzzle: Puzzle, limit: Int) -> Int {
    let n = puzzle.size
    let clueAt = puzzle.clueIndexAt
    let landTotal = puzzle.landTotal
    var marks = [Mark](repeating: .unknown, count: n * n)
    var found = 0
    func go(_ i: Int, _ land: Int) {
        if found >= limit { return }
        if land > landTotal || (i - land) > n * n - landTotal { return }
        if i == n * n {
            if Rules.isSolved(marks, puzzle: puzzle) { found += 1 }
            return
        }
        let r = i / n, c = i % n
        for colour in clueAt[i] >= 0 ? [Mark.land] : [Mark.land, .sea] {
            marks[i] = colour
            if colour == .sea, r > 0, c > 0,
               marks[i - 1] == .sea, marks[i - n] == .sea, marks[i - n - 1] == .sea {
                continue
            }
            go(i + 1, land + (colour == .land ? 1 : 0))
        }
        marks[i] = .unknown
    }
    go(0, 0)
    return found
}

// MARK: - Rules basics

do {
    let rows = BakedPuzzles.five
    let p = BakedPuzzles.decode(rows)
    let marks = p.solution.map { $0 ? Mark.land : Mark.sea }
    check(Rules.isSolved(marks, puzzle: p), "hand-made board is a valid solution")
    var broken = marks
    let firstClue = p.clues[0].cell
    broken[firstClue.row * p.size + firstClue.col] = .sea   // a clue sinks into the sea
    check(!Rules.isSolved(broken, puzzle: p), "a broken board is not solved")
    check(BakedPuzzles.encode(p) == rows, "encode round-trips")
    var pooled = marks
    for i in [0, 1, 5, 6] { pooled[i] = .sea }
    check(Rules.violations(pooled, puzzle: p, requireComplete: false).contains(.pool(corner: 0)),
          "a 2×2 of sea is reported as a pool")
    let g = Grid(size: 5)
    check(g.neighbours[0] == [1, 5] && g.neighbours[12].count == 4, "neighbour table")
    var b = Bits(); b.insert(3); b.insert(99)
    check(b.contains(3) && b.contains(99) && !b.contains(4) && b.count == 2 && b.indices == [3, 99], "Bits")
}

